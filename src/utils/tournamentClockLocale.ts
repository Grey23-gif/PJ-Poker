export function clockText(text: string, locale: ClockLocale = 'en'): string {
  return locale === 'en' ? english[text] || text : text;
}
export function clockError(message: string): string {
  return english[message] || ([...message].some((character) => character.codePointAt(0)! > 127) ? 'Unable to save this change. Check the values and try again.' : message);
}
